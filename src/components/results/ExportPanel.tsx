"use client";

import { motion } from "framer-motion";
import { useState } from "react";
import type { AnalysisResult } from "@/lib/types";

interface ExportPanelProps {
  result: AnalysisResult;
}

export default function ExportPanel({ result }: ExportPanelProps) {
  const [copied, setCopied] = useState(false);

  const handleCopy = () => {
    const text = [
      `DATAMATICS DESIGN INTELLIGENCE — ANALYSIS REPORT`,
      `Overall Score: ${result.overallScore}/100 (${result.verdict})`,
      ``,
      result.verdictSummary,
      ``,
      `--- DETAILED ANALYSIS ---`,
      ``,
      ...result.insights.map((i) => `## ${i.title}\n${i.content}\n`),
      `--- SCORECARD ---`,
      ``,
      ...result.scores.map((s) => `${s.category}: ${s.score}/100`),
    ].join("\n");

    navigator.clipboard.writeText(text).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    });
  };

  const handleDownload = () => {
    const text = [
      `DATAMATICS DESIGN INTELLIGENCE`,
      `AI-Powered Design Analysis Report`,
      `Generated: ${new Date().toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" })}`,
      `${"═".repeat(60)}`,
      ``,
      `OVERALL SCORE: ${result.overallScore}/100`,
      `VERDICT: ${result.verdict}`,
      ``,
      result.verdictSummary,
      ``,
      `${"─".repeat(60)}`,
      `DETAILED ANALYSIS`,
      `${"─".repeat(60)}`,
      ``,
      ...result.insights.map(
        (i) =>
          `▸ ${i.title.toUpperCase()}\n${"-".repeat(40)}\n${i.content}\n`
      ),
      `${"─".repeat(60)}`,
      `PERFORMANCE SCORECARD`,
      `${"─".repeat(60)}`,
      ``,
      ...result.scores.map(
        (s) =>
          `  ${s.category.padEnd(20)} ${"█".repeat(Math.round(s.score / 5))}${"░".repeat(20 - Math.round(s.score / 5))} ${s.score}/100`
      ),
      ``,
      `${"═".repeat(60)}`,
      `Report generated by Datamatics Design Intelligence v1.0`,
      `© ${new Date().getFullYear()} Datamatics. All rights reserved.`,
    ].join("\n");

    const blob = new Blob([text], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `datamatics-analysis-${Date.now()}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <motion.div
      initial={{ opacity: 0, y: 16 }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true }}
      transition={{ duration: 0.5, ease: [0.16, 1, 0.3, 1] }}
      className="flex flex-col sm:flex-row items-stretch sm:items-center gap-3"
    >
      <button
        onClick={handleDownload}
        className="inline-flex items-center justify-center gap-2.5 px-6 py-3.5 bg-text-primary text-text-inverse rounded-[12px] font-medium text-[14px]
          hover:opacity-90 active:scale-[0.98] transition-all duration-200
          shadow-[0_1px_2px_rgba(0,0,0,0.2),0_4px_12px_rgba(0,0,0,0.12)]"
      >
        <svg width="16" height="16" viewBox="0 0 16 16" fill="none">
          <path
            d="M3 10V12.5H13V10"
            stroke="currentColor"
            strokeWidth="1.3"
            strokeLinecap="round"
            strokeLinejoin="round"
          />
          <path
            d="M8 2.5V10M8 10L5.5 7.5M8 10L10.5 7.5"
            stroke="currentColor"
            strokeWidth="1.3"
            strokeLinecap="round"
            strokeLinejoin="round"
          />
        </svg>
        Download Report
      </button>

      <button
        onClick={handleCopy}
        className="inline-flex items-center justify-center gap-2.5 px-6 py-3.5 bg-[var(--surface-elevated)] border border-border-subtle text-text-primary rounded-[12px] font-medium text-[14px]
          hover:bg-surface-secondary active:scale-[0.98] transition-all duration-200"
      >
        {copied ? (
          <>
            <svg width="16" height="16" viewBox="0 0 16 16" fill="none">
              <path
                d="M3.5 8.5L6.5 11.5L12.5 5.5"
                stroke="#22C55E"
                strokeWidth="1.5"
                strokeLinecap="round"
                strokeLinejoin="round"
              />
            </svg>
            <span className="text-emerald-600">Copied</span>
          </>
        ) : (
          <>
            <svg width="16" height="16" viewBox="0 0 16 16" fill="none">
              <rect
                x="5.5"
                y="5.5"
                width="8"
                height="8"
                rx="1.5"
                stroke="currentColor"
                strokeWidth="1.2"
              />
              <path
                d="M10.5 5.5V3.5C10.5 2.67157 9.82843 2 9 2H3.5C2.67157 2 2 2.67157 2 3.5V9C2 9.82843 2.67157 10.5 3.5 10.5H5.5"
                stroke="currentColor"
                strokeWidth="1.2"
              />
            </svg>
            Copy Insights
          </>
        )}
      </button>
    </motion.div>
  );
}
